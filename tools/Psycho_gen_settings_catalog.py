#!/usr/bin/env python3
"""Generate runtime/settings/Psycho_settings_catalog.inc from the legacy inventory.

One row per settings control that holds a value (buttons, password fields and the vault, site-permission
and update-token editors are not settings). The row says the value's kind, the allowed choices for a
select, and whether a profile field backs it today. WIRED lists the keys the SettingsService applies;
everything else is refused with the step that will own it, so the settings page can say so.

  python3 tools/Psycho_gen_settings_catalog.py            # write the .inc
  python3 tools/Psycho_gen_settings_catalog.py --check    # fail if it is out of date
"""
from __future__ import annotations
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
INVENTORY = ROOT / "docs/reference/legacy-inventory.json"
OUTPUT = ROOT / "runtime/settings/Psycho_settings_catalog.inc"

# Not settings: transient editor inputs and secrets.
EXCLUDE = {"permOrigin", "permCamera", "permMicrophone", "permLocation", "permNotifications",
           "eSite", "eUser", "diagnosticsReport", "updateToken", "vaultEnabled"}
# Rows with a dedicated Profile field (the rest persist in the profile's extra-settings bag; see
# runtime/settings/Psycho_settings.cpp). Kept as documentation of which is which.
DEDICATED = {
    "search", "restore", "workspacesEnabled", "homepage", "blockAds", "blockThirdPartyCookies", "sendDNT",
    "stripReferrer", "blockAutoplay", "webRtc", "downloadDir", "askSaveLocation", "downloadNotify",
    "batterySaver", "sleepTabsMin", "theme", "accent", "hideSidebar", "highContrast", "reduceMotion",
    "showTabCloseButtons", "panicEnabled", "panicUrl", "spellCheck", "spellBuiltin", "vaultLockMin",
    "remember", "cpuLimit", "spellLangs", "spellDictUrl", "spellUserWords", "blockAllowSites", "blockCustomDomains",
}


def rows():
    inventory = json.loads(INVENTORY.read_text(encoding="utf-8"))
    out = []
    for category in inventory["settingsCategories"]:
        for control in category["controls"]:
            cid, kind, type_ = control["id"], control["kind"], control["type"]
            if kind == "button" or type_ in ("password", "button") or cid in EXCLUDE:
                continue
            if kind == "input" and type_ == "checkbox":
                shape = "Bool"
            elif kind == "textarea":
                shape = "Lines"
            elif kind == "select":
                shape = "Choice"
            elif type_ == "number":
                shape = "Number"
            else:
                shape = "Text"
            options = [o["value"] for o in control["options"]] if shape == "Choice" else []
            out.append((cid, shape, options, True))
    # Structured settings edited by the dynamic editors, not by one control: validated per key.
    for cid in ("containers", "services", "speedDial", "sitePermissions"):
        out.append((cid, "Json", [], True))
    return out


def render():
    lines = ["// Generated by tools/Psycho_gen_settings_catalog.py from docs/reference/legacy-inventory.json.",
             "// Do not edit by hand; run the script. {key, kind, choices, wired}"]
    for cid, shape, options, wired in rows():
        choices = ", ".join(json.dumps(o) for o in options)
        lines.append(f'{{"{cid}", SettingKind::{shape}, {{{choices}}}, {"true" if wired else "false"}}},')
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is out of date; run tools/Psycho_gen_settings_catalog.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(rows())} settings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
