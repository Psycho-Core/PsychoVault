#!/usr/bin/env node
// Writes the NSIS include that lists every file in the staged payload, one explicit File line
// per file, instead of letting the installer enumerate the folder with `File /r "dir/*.*"`.
//
// Why this exists
// ---------------
// On the owner's machine `File /r "build\payload/*.*"` reported
//   File: "build\payload/*.*" -> no files found.
// while the same script read `build\payload\LICENSE.txt` a few lines earlier for its license
// page. So NSIS could open a file it was given by name and could not enumerate a directory it
// was given by wildcard. Nothing about the folder was wrong: dir counted 20 top-level files,
// and building from a copy in %TEMP% failed the same way.
//
// The workaround is to stop asking NSIS to look: this walks the payload here and emits
//
//   SetOutPath "$INSTDIR\resources\app"
//   File "build\payload\resources\app\main.js"
//
// for every file, in a stable order. Paths are relative to the directory makensis runs in, so
// no absolute path (and nothing unusual) ever reaches the script.
//
// Usage: node tools/gen-filelist.mjs <payload dir> <output .nsh> [base dir]
'use strict'
import fs from 'node:fs'
import path from 'node:path'

const [payloadArg, outArg, baseArg] = process.argv.slice(2)
if (!payloadArg || !outArg) {
  console.error('usage: node tools/gen-filelist.mjs <payload dir> <output .nsh> [base dir]')
  process.exit(2)
}

const payload = path.resolve(payloadArg)
const out = path.resolve(outArg)
const base = path.resolve(baseArg || process.cwd())

if (!fs.existsSync(payload) || !fs.statSync(payload).isDirectory()) {
  console.error('payload directory does not exist: ' + payload)
  process.exit(1)
}

// Directory first, files after it, both alphabetical: the installer then creates folders in
// parent-before-child order and the archive is byte-identical for the same input.
function walk(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.name !== '.' && e.name !== '..')
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
  const dirs = []
  const files = []
  for (const e of entries) {
    const full = path.join(dir, e.name)
    if (e.isDirectory()) dirs.push(full)
    else files.push(full)
  }
  return { dirs, files }
}

const lines = []
lines.push('; generated by tools/gen-filelist.mjs - do not edit, it is rewritten every build')
lines.push('; ' + fs.readdirSync(payload).length + ' top-level entries in ' + path.basename(payload))

let fileCount = 0
let byteCount = 0
const seenDirs = new Set()

function emitDir(dir) {
  const rel = path.relative(payload, dir)
  const target = rel ? '$INSTDIR\\' + rel.split(path.sep).join('\\') : '$INSTDIR'
  if (seenDirs.has(target)) return
  seenDirs.add(target)
  lines.push('SetOutPath "' + target + '"')
}

function emitTree(dir) {
  emitDir(dir)
  const { dirs, files } = walk(dir)
  for (const f of files) {
    const rel = path.relative(base, f)
    if (/[\r\n"]/.test(rel)) throw new Error('a path that cannot be written into an NSIS script: ' + rel)
    lines.push('File "' + rel.split(path.sep).join('\\') + '"')
    fileCount += 1
    try { byteCount += fs.statSync(f).size } catch (e) { /* raced with a scanner */ }
  }
  for (const d of dirs) emitTree(d)
}

emitTree(payload)

if (fileCount === 0) {
  console.error('the payload has no files: ' + payload)
  process.exit(1)
}

lines.push('; ' + fileCount + ' files, ' + byteCount + ' bytes')
fs.writeFileSync(out, lines.join('\r\n') + '\r\n')
console.log('file list: ' + fileCount + ' files, ' + byteCount + ' bytes -> ' + out)
